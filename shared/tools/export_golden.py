"""Merges the Kotlin timeline dump with the Android copy and sound constants into one golden file.

Usage: export_golden.py <repo root> <timeline.json> <out.json>. Reads Android sources only.
"""
import json
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

root, timeline_path, out_path = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
res = root / "app/src/main/res"
audio_src = root / "app/src/main/java/app/florsent/service/audio"

# Copy shared by the breathing and "back to the present" screens.
STRING_KEYS = [
    "breathe_title", "breathe_start", "breathe_ambient_sound", "breathe_cue_sound", "breathe_cycle",
    "breathe_end_early", "phase_inhale", "phase_hold_in", "phase_exhale", "phase_hold_out",
    "pattern_duration", "pattern_duration_even",
    "pattern_equal", "pattern_equal_desc", "pattern_box", "pattern_box_desc",
    "pattern_478", "pattern_478_desc", "pattern_resonance", "pattern_resonance_desc",
    "grounding_label", "grounding_another", "grounding_return", "grounding_return_bedtime", "grounding_cooldown",
    "home_breathe_now", "greeting_morning", "greeting_afternoon", "greeting_evening", "greeting_night",
    "settings_title", "settings_ambient", "settings_ambient_hint", "settings_cue_hint",
    "settings_fade_sound", "nudge_message", "nudge_accept_description", "nudge_dismiss_description",
    "onboarding_step_breathe", "settings_row_breathing", "settings_section_appearance", "settings_section_guidance",
    "settings_language", "settings_footer", "today_label", "minutes_format",
]
ARRAY_KEYS = ["grounding_prompts", "grounding_prompts_bedtime"]


def unescape(text: str) -> str:
    return (text or "").replace("\\'", "'").replace('\\"', '"').replace("\\n", "\n")


def read_strings(path: Path) -> dict:
    tree = ET.parse(path).getroot()
    strings = {e.get("name"): unescape(e.text) for e in tree.findall("string")}
    arrays = {e.get("name"): [unescape(i.text) for i in e.findall("item")] for e in tree.findall("string-array")}
    plurals = {
        e.get("name"): {i.get("quantity"): unescape(i.text) for i in e.findall("item")} for e in tree.findall("plurals")
    }
    missing = [k for k in STRING_KEYS if k not in strings] + [k for k in ARRAY_KEYS if k not in arrays]
    if missing:
        sys.exit(f"{path}: missing {missing}")
    return {
        "strings": {k: strings[k] for k in STRING_KEYS},
        "arrays": {k: arrays[k] for k in ARRAY_KEYS},
        "plurals": {"breathe_countdown_description": plurals["breathe_countdown_description"]},
    }


def const(source: str, name: str) -> float:
    m = re.search(rf"const val {name} = ([0-9_.]+)[fL]?", source)
    if not m:
        sys.exit(f"constant {name} not found")
    return float(m.group(1).replace("_", ""))


soundscape = (audio_src / "BreathingSoundscape.kt").read_text()
fade = (audio_src / "FadeSound.kt").read_text()
rates = dict(re.findall(r"BreathPhaseKind\.(\w+) -> ([0-9.]+)f", soundscape))
kind_ids = {"Inhale": "inhale", "HoldIn": "holdIn", "Exhale": "exhale", "HoldOut": "holdOut"}

golden = json.loads(timeline_path.read_text())
golden = {
    "schemaVersion": 1,
    "source": "Generated by shared/tools/export_golden.sh from the Android app (Breathing.kt, strings.xml, "
    "BreathingSoundscape.kt, FadeSound.kt). Times in ms; expansion/progress are Kotlin Float (compare within 1e-5).",
    **golden,
    "sound": {
        "ambientVolume": const(soundscape, "AMBIENT_VOLUME"),
        "cueVolume": const(soundscape, "CUE_VOLUME"),
        "ambientFadeInMs": int(const(soundscape, "FADE_IN_MS")),
        "ambientFadeOutMs": int(const(soundscape, "FADE_OUT_MS")),
        "cueRate": {kind_ids[k]: float(v) for k, v in rates.items()},
        "fadeRainTargetVolume": const(fade, "TARGET_VOLUME"),
        "ambientLoopFrames": {"breathing_ambient": 48 * 48000, "fade_ambient": 42 * 48000},
    },
    "copy": {
        "en": read_strings(res / "values/strings.xml"),
        "zh-Hant": read_strings(res / "values-zh-rTW/strings.xml"),
    },
}
out_path.write_text(json.dumps(golden, ensure_ascii=False, indent=1) + "\n")
p = golden["patterns"]
print(f"wrote {out_path}: {len(p)} patterns, {sum(len(x['samples']) for x in p)} samples, "
      f"{len(golden['copy']['zh-Hant']['arrays']['grounding_prompts']) + len(golden['copy']['zh-Hant']['arrays']['grounding_prompts_bedtime'])} grounding prompts")
